"""Generate src/vartable.h (XBeach output-variable names, shapes, units and descriptions) from XBeach's
variables.def.  Usage: python tools/gen_vartable.py <path to xbeachlibrary/variables.def> > src/vartable.h"""
import json
import re
import sys

rows = []
for line in open(sys.argv[1], encoding="latin-1"):
    m = re.match(r"\s*(double precision|integer|character\(\w+\)),.*::\s*(\w+)(\([:,]*\))?\s*!<\s*\[([^\]]*)\]\s*(.*?)\s*(\{.*\})\s*$", line)
    if not m:
        continue
    typ, name, dims, units, desc, js = m.groups()
    meta = json.loads(js)
    shape = meta.get("shape", [])
    t = "r" if typ.startswith("double") else ("i" if typ == "integer" else "c")
    if t == "c":
        continue
    sh = ",".join(str(s).replace("s%", "").replace("par%", "") for s in shape)
    rows.append((name, t, len(shape), sh, units, desc.replace('"', "'"), meta.get("standard_name", "")))

print("// vartable.h: generated by tools/gen_vartable.py from XBeach r6167 variables.def (LGPL). Do not edit.")
print("#pragma once")
print("struct VarInfo { const char *name; char type; int rank; const char *shape, *units, *description, *standard_name; };")
print("static const VarInfo XB_VARS[] = {")
for r in rows:
    print('    {"%s", \'%s\', %d, "%s", "%s", "%s", "%s"},' % r)
print("};")
print("static const int XB_NVARS = %d;" % len(rows))
