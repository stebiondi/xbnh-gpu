"""
Build an XBeach non-hydrostatic test deck that runs unchanged in Fortran XBeach and in xbnh_gpu.

Barred beach with a rip channel at 2 m resolution:
  - offshore depth 8 m, plane slope 1:50 up to +2 m (dry beach at the back of the domain),
  - shore-parallel bar (Gaussian, 1.5 m high, 25 m e-folding half-width) at x = 300 m, crest 0.5 m deep,
  - rip channels through the bar (60 m wide, every 300 m alongshore, first at y = 150 m), so the flow is 2D.
Forcing: irregular long-crested waves at the offshore boundary (wbctype = ts_nonh, scalar boun_U.bcf):
  JONSWAP Hm0 = 1.0 m, Tp = 8 s, gamma = 3.3, 300 components (fixed seed), linear depth-averaged
  velocity U = a omega / (k h), 20 s cosine ramp. Back wall, Neumann laterals, no wind, zs0 = 0.

The domain is scaled by keeping dx = dy and the cross-shore profile and stretching the alongshore length,
so the cell count grows while the physics per metre of coast stays identical.

Usage:
  python examples/rip_beach/make_case.py <case dir> --ny 200 --dx 2 --tstop 300 --tintg 1
"""
import argparse
from pathlib import Path

import numpy as np

G = 9.81


def dispersion(w, h):
    k = w * w / G
    for _ in range(100):
        k = k - (G * k * np.tanh(k * h) - w * w) / (G * np.tanh(k * h) + G * k * h / np.cosh(k * h) ** 2)
    return k


def bathymetry(nx, ny, dx):
    x = np.arange(nx + 1) * dx
    y = np.arange(ny + 1) * dx
    X, Y = np.meshgrid(x, y)                         # shape (ny+1, nx+1), i fastest as XBeach
    zb = -8.0 + X / 50.0                             # 1:50 to +2 m at x = 500 m
    xbar = 300.0                                     # crest at -2 m before the bar: -8 + 300/50 = -2
    bar = 1.5 * np.exp(-((X - xbar) / 25.0) ** 2)
    yr = np.mod(Y, 300.0) - 150.0                    # rip channels 60 m wide every 300 m alongshore
    gap = 1.0 - np.exp(-(yr / 30.0) ** 4)
    zb = zb + bar * gap
    return np.minimum(zb, 2.0 + 0.0 * zb)


def boundary(tstop, h0, hm0=1.0, tp=8.0, gamma=3.3, ncomp=300, seed=42, dt=0.1, ramp=20.0):
    f = np.linspace(0.05, 0.30, ncomp)
    df = f[1] - f[0]
    fp = 1.0 / tp
    sig = np.where(f <= fp, 0.07, 0.09)
    S = f ** -5 * np.exp(-1.25 * (fp / f) ** 4) * gamma ** np.exp(-((f - fp) ** 2) / (2 * sig ** 2 * fp ** 2))
    S *= (hm0 / 4.0) ** 2 / (S.sum() * df)
    a = np.sqrt(2 * S * df)
    w = 2 * np.pi * f
    k = dispersion(w, h0)
    phi = np.random.default_rng(seed).uniform(0, 2 * np.pi, ncomp)
    t = np.arange(0.0, tstop + 10.0 + dt / 2, dt)
    arg = np.outer(t, w) + phi
    z = (a * np.cos(arg)).sum(axis=1)
    u = (a * w / (k * h0) * np.cos(arg)).sum(axis=1)
    r = np.where(t < ramp, 0.5 - 0.5 * np.cos(np.pi * t / ramp), 1.0)
    return t, u * r, z * r


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("case")
    ap.add_argument("--nx", type=int, default=0, help="default: 520 m cross-shore / dx")
    ap.add_argument("--ny", type=int, default=200)
    ap.add_argument("--dx", type=float, default=2.0)
    ap.add_argument("--tstop", type=float, default=300.0)
    ap.add_argument("--tintg", type=float, default=1.0)
    ap.add_argument("--noout", action="store_true", help="benchmark mode: global output only at the end")
    a = ap.parse_args()
    nx = a.nx or int(round(520.0 / a.dx))
    out = Path(a.case)
    out.mkdir(parents=True, exist_ok=True)
    zb = bathymetry(nx, a.ny, a.dx)
    np.savetxt(out / "z.grd", zb, fmt="%.4f")
    t, u, z = boundary(a.tstop, -zb[0, 0])
    with open(out / "boun_U.bcf", "w") as fh:
        fh.write("scalar\n3\nt u z\n")
        for row in zip(t, u, z):
            fh.write("%.3f %.6f %.6f\n" % row)
    tintg = a.tstop if a.noout else a.tintg
    params = f"""%% XBeach-NH test deck, generated by scripts/data/01_make_case.py
nx          = {nx}
ny          = {a.ny}
dx          = {a.dx}
dy          = {a.dx}
vardx       = 0
depfile     = z.grd
posdwn      = -1
wavemodel   = nonh
wbctype     = ts_nonh
front       = nonh_1d
back        = wall
left        = neumann
right       = neumann
zs0         = 0.0
sedtrans    = 0
morphology  = 0
tstart      = 0
tstop       = {a.tstop}
tintg       = {tintg}
outputformat    = fortran
outputprecision = double
nglobalvar  = 3
zs
u
v
"""
    (out / "params.txt").write_text(params)
    print(f"{out}: nx={nx} ny={a.ny} cells={(nx + 1) * (a.ny + 1)} h0={-zb[0, 0]:.2f} m")


if __name__ == "__main__":
    main()
