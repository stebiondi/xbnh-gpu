"""
Build the Estero-feature test deck: every XBeach option the estero T0 deck uses, on a small domain that
runs in minutes in Fortran XBeach (MPI) and in xbnh_gpu.

  - cyclic = 1 laterals (XBeach needs MPI for this); bathymetry periodic with the XBeach MPI period
    (ny - 3 rows): barred profile with one rip channel per 300 m (ny = 153, dy = 2 m),
  - wbctype = reuse with a vector nh_series file (t, U, V, Z along the whole offshore boundary):
    short-crested JONSWAP sea (Hm0 = 1 m, Tp = 8 s, mean direction 20 deg from shore-normal), each
    component snapped to an alongshore wavenumber that is periodic over the domain,
  - back = abs_2d on a wet back boundary (2 m deep shelf, so the absorbing condition is active),
  - tide from zs0file (tideloc = 1), time-varying wind from windfile,
  - point output (npoints) and global output, writehotstart at t = 100 s for the hotstart test.
outputformat is listed twice, as in the estero deck: with a single statement, trunk r6167 reaches a
malformed format string in postprocess.F90 snappointstogrid ('i0'') and stops with a runtime error.

Usage:
  python examples/estero_features/make_case.py <case dir> [--tstop 200]
"""
import argparse
from pathlib import Path

import numpy as np

G = 9.81


def dispersion(w, h):
    k = w * w / G
    for _ in range(100):
        k = k - (G * k * np.tanh(k * h) - w * w) / (G * np.tanh(k * h) + G * k * h / np.cosh(k * h) ** 2)
    return k


def bathymetry(nx, ny, dx, period):
    x = np.arange(nx + 1) * dx
    y = np.arange(ny + 1) * dx
    X, Y = np.meshgrid(x, y)                          # (ny+1, nx+1), i fastest as XBeach
    zb = np.minimum(-8.0 + X / 50.0, -2.0)            # 1:50 slope onto a 2 m deep shelf from x = 300 m
    yr = np.mod(Y, period) - 0.5 * period             # one rip channel per period, 60 m wide
    gap = 1.0 - np.exp(-(yr / 30.0) ** 4)
    zb = zb + 1.8 * np.exp(-((X - 250.0) / 20.0) ** 2) * gap   # bar crest about 1.2 m deep at x = 250 m
    return zb


def boundary(t, y, h0, period, hm0=1.0, tp=8.0, gamma=3.3, ncomp=200, dir0=20.0, spread=10.0, seed=7):
    rng = np.random.default_rng(seed)
    f = np.linspace(0.06, 0.25, ncomp)
    df = f[1] - f[0]
    fp = 1.0 / tp
    sig = np.where(f <= fp, 0.07, 0.09)
    S = f ** -5 * np.exp(-1.25 * (fp / f) ** 4) * gamma ** np.exp(-((f - fp) ** 2) / (2 * sig ** 2 * fp ** 2))
    S *= (hm0 / 4.0) ** 2 / (S.sum() * df)
    a = np.sqrt(2 * S * df)
    w = 2 * np.pi * f
    k = dispersion(w, h0)
    th = np.deg2rad(dir0 + spread * rng.standard_normal(ncomp))
    m = np.round(k * np.sin(th) * period / (2 * np.pi))         # integer number of crests per period
    ky = 2 * np.pi * m / period
    th = np.arcsin(np.clip(ky / k, -1, 1))
    phi = rng.uniform(0, 2 * np.pi, ncomp)
    ramp = np.where(t < 20.0, 0.5 - 0.5 * np.cos(np.pi * t / 20.0), 1.0)
    U = np.zeros((t.size, y.size)); V = np.zeros_like(U); Z = np.zeros_like(U)
    for q in range(ncomp):
        arg = ky[q] * y[None, :] - w[q] * t[:, None] + phi[q]
        c = a[q] * np.cos(arg)
        Z += c
        U += c * w[q] / (k[q] * h0) * np.cos(th[q])
        V += c * w[q] / (k[q] * h0) * np.sin(th[q])
    return U * ramp[:, None], V * ramp[:, None], Z * ramp[:, None]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("case")
    ap.add_argument("--tstop", type=float, default=200.0)
    a = ap.parse_args()
    nx, ny, dx = 260, 153, 2.0
    period = (ny - 3) * dx                            # XBeach MPI cyclic period: rows j and j + ny - 3 coincide
    out = Path(a.case)
    out.mkdir(parents=True, exist_ok=True)
    zb = bathymetry(nx, ny, dx, period)
    np.savetxt(out / "z.grd", zb, fmt="%.4f")
    h0 = -zb[0, 0]
    t = np.arange(0.0, 2 * a.tstop + 0.05, 0.1)
    y = np.arange(ny + 1) * dx
    U, V, Z = boundary(t, y, h0, period)
    with open(out / "nh_series00001.bcf", "w") as fh:
        fh.write("vector\n4\nt,U,V,Z\n")
        for n in range(t.size):
            fh.write(" ".join(["%.4f" % t[n]] + ["%.6e" % v for v in np.concatenate([U[n], V[n], Z[n]])]) + "\n")
    (out / "nhbcflist.bcf").write_text("%.3f %.3f 8.0 0.7 nh_series00001.bcf\n" % (0.0, 2 * a.tstop))
    (out / "water_elev.dat").write_text("0.0 0.0\n%.1f 0.40\n" % (2 * a.tstop))
    (out / "wind.txt").write_text("0.0 10.0 240.0\n%.1f 15.0 250.0\n" % (2 * a.tstop))
    pts = [(250.0, 150.0, "rip"), (250.0, 50.0, "bar"), (200.0, 150.0, "offbar"), (400.0, 100.0, "shelf"),
           (510.0, 150.0, "back"), (250.0, 0.0, "seam_lo"), (250.0, 300.0, "seam_hi")]
    params = f"""%% Estero-feature test deck, generated by scripts/data/06_make_cyclic_case.py
nx          = {nx}
ny          = {ny}
dx          = {dx}
dy          = {dx}
vardx       = 0
depfile     = z.grd
posdwn      = -1
cyclic      = 1
mpiboundary = x
wavemodel   = nonh
wbctype     = reuse
taper       = 0
zs0file     = water_elev.dat
tideloc     = 1
wind        = 1
windfile    = wind.txt
sedtrans    = 0
morphology  = 0
tstart      = 0
tstop       = {a.tstop}
tintg       = 1.0
tintp       = 0.5
writehotstart = 1
tinth       = 100.0
outputformat    = fortran
outputformat    = fortran
outputprecision = double
nglobalvar  = 3
zs
u
v
npoints     = {len(pts)}
""" + "".join(f"{x:.1f} {yy:.1f} {nm}\n" for x, yy, nm in pts) + """npointvar   = 5
zs
uu
vv
u
v
"""
    (out / "params.txt").write_text(params)
    print(f"{out}: nx={nx} ny={ny} period={period} m h0={h0:.2f} m")


if __name__ == "__main__":
    main()
